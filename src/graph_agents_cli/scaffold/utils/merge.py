"""Shared merge utilities for upgrade and enhance commands.

Functions for generating template snapshots, displaying comparison results,
resolving conflicts, and applying file changes. ``run_three_way_merge`` is the
orchestrator shared by *upgrade* and *enhance*.

Baseline policy: the old snapshot is regenerated by the exact prior CLI
version (``uvx --from <pinned_install_spec(version)> graph-agents-cli``), because
the current templates would misclassify files that changed between the two
versions. When that version cannot be fetched and run, or
``GRAPH_AGENTS_CLI_INSTALL_SPEC`` is set without ``{version}`` (it would install
some other build), the merge stops with no changes unless ``baseline="current"``
was passed, an explicit and logged opt-in to compare against the current templates.
"""

